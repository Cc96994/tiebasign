#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""patch_base_java.py - 把仓库里的 Java 补丁打进 p4a 底座（幂等）。

为什么需要这个脚本
------------------
这个 App 的原生能力（原生登录、保活服务、Keystore、以及本次的安装入口）
都住在 **仓库之外** 的 p4a 底座里：

    <p4a.source_dir>/pythonforandroid/bootstraps/webview/build/
        src/main/java/org/kivy/android/PythonActivity.java
        src/main/java/org/dsh/tiebaweb/*.java
        templates/AndroidManifest.tmpl.xml

以前这些改动是"在某台机器上手工改的"，结果就是：换一台机器、或者重装一次
p4a，这些能力会静默消失（Python 侧只会打印一句"方法未找到"）。本脚本把
"仓库 -> 底座"这一步变成可重复执行的动作：

  1. 把 java_src/org/**/*.java 拷进底座源码树；
  2. 把 java_src/PythonActivity.updater.inc 整段插进 PythonActivity.java
     的标记之间；
  3. 把 <provider> 声明插进 AndroidManifest.tmpl.xml 的标记之间；
  4. 反向校验：updater.py 里反射调用的每个方法名，都能在打好补丁的
     PythonActivity.java 里找到定义（名字写错就当场失败，而不是等到用户
     点"安装"时才失败）。

幂等：重复执行先删旧块再插新块；再跑一次结果逐字节相同。

用法：
    python3 scripts/patch_base_java.py [--p4a /home/s7909/p4a-develop] [--check]
    --check  只校验，不写任何文件（CI / 构建前用）
"""

import argparse
import os
import re
import shutil
import sys

JAVA_BEGIN = "    // >>> TiebaSignUpdaterMethods (generated by scripts/patch_base_java.py)"
JAVA_END = "    // <<< TiebaSignUpdaterMethods"
MAN_BEGIN = "        <!-- >>> TiebaSignUpdaterProvider (generated by scripts/patch_base_java.py) -->"
MAN_END = "        <!-- <<< TiebaSignUpdaterProvider -->"

PROVIDER_XML = (
    '        <provider\n'
    '                android:name="org.dsh.tiebaweb.ApkProvider"\n'
    '                android:authorities="{{ args.package }}.apkprovider"\n'
    '                android:exported="false"\n'
    '                android:grantUriPermissions="true" />\n'
)


def die(msg):
    print("patch_base_java: ERROR: {}".format(msg), file=sys.stderr)
    sys.exit(1)


def read(path):
    with open(path, "r", encoding="utf-8") as fh:
        return fh.read()


def write(path, text):
    tmp = path + ".patchtmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(text)
    os.replace(tmp, path)


def splice(text, begin, end, block, anchor_re, what):
    """把 block 放进 text 的 begin/end 标记之间；没有标记就在 anchor 前插入。

    anchor_re 是"块应该插在哪一行之前"的正则（只在首次插入时用）。
    """
    block = block if block.endswith("\n") else block + "\n"
    has_begin = begin in text
    has_end = end in text
    if has_begin != has_end:
        die("{}: 标记不成对（只有开始或只有结束），拒绝猜测，请手工检查".format(what))
    if has_begin:
        head, rest = text.split(begin, 1)
        _old, tail = rest.split(end, 1)
        return head + begin + "\n" + block + end + tail
    lines = text.splitlines(keepends=True)
    for idx, line in enumerate(lines):
        if re.match(anchor_re, line):
            return "".join(lines[:idx]) + begin + "\n" + block + end + "\n" + \
                "".join(lines[idx:])
    die("{}: 找不到插入锚点（{}）".format(what, anchor_re))


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    proj = os.path.dirname(here)

    ap = argparse.ArgumentParser()
    ap.add_argument("--p4a", default=os.environ.get("P4A_SRC",
                                                    "/home/s7909/p4a-develop"))
    ap.add_argument("--java-src", default=os.path.join(proj, "java_src"))
    ap.add_argument("--dist-root",
                    default=os.path.join(
                        proj, ".buildozer", "android", "platform",
                        "build-arm64-v8a", "dists"),
                    help="既有的 dists 目录（p4a 的缓存副本，见下面的注释）")
    ap.add_argument("--dist-name", default=None,
                    help="只同步这个 dist（默认读 spec 的 package.name）；"
                         "其它 dist 属于别的构建，不该被本工程的补丁碰到")
    ap.add_argument("--check", action="store_true",
                    help="只校验，不写文件")
    args = ap.parse_args()

    boot = os.path.join(args.p4a, "pythonforandroid", "bootstraps", "webview",
                        "build")
    java_root = os.path.join(boot, "src", "main", "java")
    activity = os.path.join(java_root, "org", "kivy", "android",
                            "PythonActivity.java")
    manifest = os.path.join(boot, "templates", "AndroidManifest.tmpl.xml")
    inc = os.path.join(args.java_src, "PythonActivity.updater.inc")
    updater_py = os.path.join(proj, "app", "updater.py")

    for path in (activity, manifest):
        if not os.path.isfile(path):
            die("底座文件不存在：{}（--p4a 指对了吗？）".format(path))
    if not os.path.isfile(inc):
        die("补丁片段不存在：{}".format(inc))

    # ---- 1. java_src/org/**/*.java -> 底座源码树 --------------------------
    copied = []
    src_org = os.path.join(args.java_src, "org")
    if not os.path.isdir(src_org):
        die("找不到 {}（仓库里的 Java 源码目录）".format(src_org))
    for root, _dirs, files in os.walk(src_org):
        for name in sorted(files):
            if not name.endswith(".java"):
                continue
            src = os.path.join(root, name)
            rel = os.path.relpath(src, args.java_src)
            dst = os.path.join(java_root, rel)
            same = os.path.isfile(dst) and read(dst) == read(src)
            copied.append((rel, "unchanged" if same else "copied"))
            if not same and not args.check:
                os.makedirs(os.path.dirname(dst), exist_ok=True)
                shutil.copyfile(src, dst)

    # ---- 2. PythonActivity.java 片段 -------------------------------------
    # 锚点是"文件里第一个顶格的 }"，也就是 public class PythonActivity 的结尾。
    # 实测该文件只有 3 个顶格 }（975 / 984 / 992 行），后两个是文件末尾的
    # PythonMain / WebViewLoaderMain 两个独立顶层类 —— 所以**绝不能用最后一个**，
    # 否则方法会被插进 WebViewLoaderMain 里，直接编译不过。
    text = read(activity)
    closers = [i for i, ln in enumerate(text.splitlines()) if re.match(r"^}\s*$", ln)]
    if not closers or "public class PythonActivity" not in text[:2000]:
        die("PythonActivity.java 结构不符合预期（找不到顶格 } / 类声明），拒绝改")
    patched = splice(text, JAVA_BEGIN, JAVA_END, read(inc),
                     r"^}\s*$", "PythonActivity.java")

    # ---- 3. manifest <provider> ------------------------------------------
    man = read(manifest)
    man_patched = splice(man, MAN_BEGIN, MAN_END, PROVIDER_XML,
                         r"^\s*</application>\s*$", "AndroidManifest.tmpl.xml")

    # ---- 4. 契约校验：updater.py 反射调用的方法必须都存在 -----------------
    if os.path.isfile(updater_py):
        names = sorted(set(re.findall(
            r'_call_static_raw\(\s*"([A-Za-z_][A-Za-z0-9_]*)"', read(updater_py))))
        missing = []
        for name in names:
            if not re.search(r"\b(?:public|private|protected)\s+static\s+"
                             r"[A-Za-z_<>\[\]]+\s+" + re.escape(name) + r"\s*\(",
                             patched):
                missing.append(name)
        if missing:
            die("updater.py 会反射调用但这些方法在补丁后的 PythonActivity.java "
                "里不存在：{}".format(", ".join(missing)))
        have_bridge = len(re.findall(r"\bstatic\s+[A-Za-z_<>\[\]]+\s+\w+\s*\(", patched))
        print("   contract: {} 个方法名全部有定义（补丁后共 {} 个静态方法）"
              .format(len(names), have_bridge))
        print("   contract: {}".format(", ".join(names)))
    else:
        print("   contract: 跳过（找不到 {}）".format(updater_py))

    # ---- 5. 既有 dists 里的缓存副本 --------------------------------------
    # p4a 只在**创建** dist 时把 bootstrap 的 build 目录拷进 dists/<name>/，
    # 之后复用这个 dist 就再也不刷新。实测过一次：p4a 底座改好、bootstrap_builds
    # 也已经刷新，但构建出来的 APK 里新方法一个都没有 —— 因为编译的是
    # dists/tiebaweb/src/main/java 里 8 月 24 日那份 PythonActivity.java
    # （classes*.dex 里 installApk 计数 0），manifest 也没有 <provider>，
    # 因为 render() 读的是 dists/tiebaweb/templates/ 里那份旧模板。
    # 所以：对每个既有 dist 把同样三件事再做一遍。新机器上没有 dist，这步是空转，
    # 但那时 dist 会用已经打过补丁的底座源码新建，结果一致。
    dist_changes = []
    dist_names = []
    dist_filter = args.dist_name
    if dist_filter is None:
        spec = os.path.join(proj, "buildozer_webview_app.spec")
        if os.path.isfile(spec):
            match = re.search(r"^package\.name\s*=\s*(\S+)\s*$", read(spec),
                              re.MULTILINE)
            if match:
                dist_filter = match.group(1)
    if os.path.isdir(args.dist_root):
        dist_names = sorted(
            n for n in os.listdir(args.dist_root)
            if os.path.isdir(os.path.join(args.dist_root, n))
            and (dist_filter is None or n == dist_filter))

    def sync_dist(dist):
        changed_here = []
        java_root = os.path.join(dist, "src", "main", "java")
        d_act = os.path.join(java_root, "org", "kivy", "android",
                            "PythonActivity.java")
        if not os.path.isfile(d_act):
            # 这个 dist 不是用本 bootstrap 建的（或还没建），整块跳过。
            # 判据是"有没有那个底座 Activity"，而不是逐个文件看存在与否 ——
            # 后者会把 ApkProvider.java 这种**新文件**当成"与本 dist 无关"而漏掉。
            return changed_here
        for root, _dirs, files in os.walk(src_org):
            for fname in sorted(files):
                if not fname.endswith(".java"):
                    continue
                src = os.path.join(root, fname)
                rel = os.path.relpath(src, args.java_src)
                dst = os.path.join(java_root, rel)
                if os.path.isfile(dst) and read(dst) == read(src):
                    continue
                changed_here.append(rel)
                if not args.check:
                    os.makedirs(os.path.dirname(dst), exist_ok=True)
                    shutil.copyfile(src, dst)
        old = read(d_act)
        new = splice(old, JAVA_BEGIN, JAVA_END, read(inc),
                     r"^}\s*$",
                     "{}:PythonActivity.java".format(os.path.basename(dist)))
        if new != old:
            changed_here.append("org/kivy/android/PythonActivity.java")
            if not args.check:
                write(d_act, new)
        d_man = os.path.join(dist, "templates", "AndroidManifest.tmpl.xml")
        if os.path.isfile(d_man):
            old = read(d_man)
            new = splice(old, MAN_BEGIN, MAN_END, PROVIDER_XML,
                         r"^\s*</application>\s*$",
                         "{}:AndroidManifest.tmpl.xml".format(
                             os.path.basename(dist)))
            if new != old:
                changed_here.append("templates/AndroidManifest.tmpl.xml")
                if not args.check:
                    write(d_man, new)
        return changed_here

    for name in dist_names:
        for rel in sync_dist(os.path.join(args.dist_root, name)):
            dist_changes.append("{}/{}".format(name, rel))

    # ---- 写入 -------------------------------------------------------------
    changed = []
    if patched != text:
        changed.append("PythonActivity.java")
        if not args.check:
            write(activity, patched)
    if man_patched != man:
        changed.append("AndroidManifest.tmpl.xml")
        if not args.check:
            write(manifest, man_patched)

    print("   java_src -> 底座：")
    for rel, state in copied:
        print("     {}  {}".format(state, rel))
    if dist_names:
        print("   既有 dists（{} 个）：{}".format(
            len(dist_names), ", ".join(dist_names)))
        for rel in dist_changes:
            print("     同步  {}".format(rel))
        if not dist_changes:
            print("     全部已是最新")
    else:
        print("   既有 dists：无（{} 不存在，新构建会从底座新建）".format(
            args.dist_root))
    print("   {}{}".format(
        "只校验，未写文件；将改动：" if args.check else "已写入：",
        ", ".join(changed) if changed else "（无需改动，已是最新）"))
    print("PATCH_BASE_JAVA_OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
